let current: Lang = 'zh-CN';

/**
 * Switch the active dictionary. Emits `lang:changed` only when the value really
 * moves: the settings modal calls this on every save, and a full relabel on each
 * keystroke would be wasteful.
 */
export function setLang(lang: string) {
  const next = (DICTS[lang as Lang] ? lang : 'en-US') as Lang;
  const changed = next !== current;
  current = next;
  document.documentElement.lang = current;
  // index.html paints the boot card before this module exists; it reads the
  // cached language so the second start does not flash the OS locale.
  try {
    localStorage.setItem('irixen.lang', current);
  } catch {
    /* private mode — the splash falls back to navigator.language */
  }
  if (changed) emit('lang:changed', current);
}

export function getLang(): Lang {
  return current;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const dict: Dict = DICTS[current];
  const fallback: Dict = enUS;
  let s = dict?.[key] ?? fallback[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  // A template that still has placeholders must never reach the UI as a
  // literal `{pid}`. Callers normally supply every variable, but a missing one
  // (or a translation with an extra token) used to render those braces.
  return s.replace(/\{[A-Za-z][A-Za-z0-9_]*\}/g, '');
}
